static uint16 camera_sequence = 0;  // 模拟摄像头帧序号，取值范围为 0-65535。

//-------------------------------------------------------------------------------------------------------------------
// 函数功能：将 UART0 配置为模拟摄像头数据输出接口。
// 说明：UART0 使用与摄像头接口相同的 921600 波特率及 A10/A11 引脚。
//-------------------------------------------------------------------------------------------------------------------
static void uart0_init_camera_simulator(void)
{
  uart_init(UART_0, 921600, UART0_TX_A10, UART0_RX_A11);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数功能：使用 POS ASCII 协议发送一帧模拟摄像头数据。
// 说明：距离为 1000 mm 时，x=305、y=230 可使参考接收端修正后的两个偏移量均为 0。
//-------------------------------------------------------------------------------------------------------------------
static void uart0_send_camera_frame(void)
{
  uint8 camera_frame[32];  // 存放一帧完整 POS 协议数据的缓冲区。
  uint32 camera_frame_length;  // 当前 POS 协议数据帧的字节数。

  camera_frame_length = (uint32)sprintf((char *)camera_frame, "POS,1,%u,305,230,1000\n", camera_sequence);
  uart_write_buffer(UART_0, camera_frame, camera_frame_length);
  camera_sequence = camera_sequence + 1;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数功能：初始化系统时钟，并以标称 40 Hz 持续发送模拟摄像头数据帧。
//-------------------------------------------------------------------------------------------------------------------
int main(void)
{
  clock_init(SYSTEM_CLOCK_80M);  // 初始化 UART0 前先配置系统时钟。
  uart0_init_camera_simulator();
	gpio_init(B22,GPI,GPIO_HIGH,GPI_PULL_UP);
  while(1)
  {
    uart0_send_camera_frame();
    system_delay_ms(25);  // 每帧间隔 25 ms，对应标称 40 帧每秒。
  }
}