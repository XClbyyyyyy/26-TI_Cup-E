#include "zf_common_headfile.h"
#include "timer_config.h"
#include "uart_config.h"  // 引用 left_speed, right_speed

//-------------------------------------------------------------------------------------------------------------------
// 全局变量定义
//-------------------------------------------------------------------------------------------------------------------
volatile uint32 system_timer_ms = 0;  // 系统定时器计数(毫秒)
volatile float  total_pulses    = 0;  // 累积脉冲数

// left_speed, right_speed, and state are defined in uart_config.c; circle and out_of_line are defined in main.c.
extern uint8 circle;
extern uint8 state;
extern volatile uint8 out_of_line;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     定时器中断回调函数
// 参数说明     event           触发中断的事件
// 参数说明     *ptr            回调参数指针
// 返回参数     void
// 使用示例     由中断自动调用
// 备注信息     1ms 周期中断, 累积脉冲 → 圈数
//               跑道: 1m正方形, 轮周20cm → 20圈车轮；10:1减速比后为200圈电机
//               一圈目标: 200 × 3200 = 640000个电机脉冲
//               每ms脉冲 = speed * 3200/60000 = speed * 0.05333...
//-------------------------------------------------------------------------------------------------------------------
static void timer_pit_callback(uint32 event, void *ptr)
{
  float avg_speed;  // 左右轮平均速度

  system_timer_ms++;

  if(state == 0)
    total_pulses = 0;  // 待机时清除模拟脉冲，防止后台继续累积
  else if(out_of_line == 0)  // 出线时不累积里程
  {
    avg_speed = (left_speed + right_speed) * 0.5f;
    total_pulses += avg_speed * 3200/60000;
  }

  if(circle > 0 && total_pulses >= circle * (688000.0f))  // 每圈赛道额外补偿1.5圈车轮(48000电机脉冲)
  {
    state = 0;
    total_pulses = 0;
  }
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     定时器配置初始化
// 返回参数     void
// 使用示例     timer_config_init();
// 备注信息     初始化 TIMG12 定时器, 1ms 周期中断
//-------------------------------------------------------------------------------------------------------------------
void timer_config_init(void)
{
  pit_ms_init(PIT_TIM_G12, 1, timer_pit_callback, NULL);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     获取系统时间(毫秒)
// 返回参数     uint32          系统运行时间(毫秒)
// 使用示例     uint32 time = get_system_time_ms();
// 备注信息     返回自系统启动以来的毫秒数
//-------------------------------------------------------------------------------------------------------------------
uint32 get_system_time_ms(void)
{
  return system_timer_ms;
}
