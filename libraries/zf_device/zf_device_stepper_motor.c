void motor_stop(uint8 addr)
{
  uint8 cmd[5] = {0};  // 急停完整协议命令

  cmd[0] = addr;
  cmd[1] = 0xFE;
  cmd[2] = 0x98;
  cmd[3] = 0;
  cmd[4] = 0x6B;

  motor_save_cmd(cmd, 5);
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     设置电机位置模式命令
// 参数说明     addr - 电机地址
// 参数说明     dir - 方向: 0=顺时针, 1=逆时针
// 参数说明     vel - 速度，单位: RPM，范围: 0-5000
// 参数说明     acc - 加速度，范围: 0-255，0 表示直接启动
// 参数说明     clk - 脉冲数，范围: 0-4294967295
// 参数说明     raF - 位置模式: 0=绝对位置, 1=相对位置
//-------------------------------------------------------------------------------------------------------------------
void motor_pos_control(uint8 addr, uint8 dir, uint16 vel, uint8 acc, uint32 clk, uint8 raF)
{
  uint8 cmd[13] = {0};  // 位置模式完整协议命令

  cmd[0] = addr;
  cmd[1] = 0xFD;
  cmd[2] = dir;
  cmd[3] = (uint8)(vel >> 8);
  cmd[4] = (uint8)(vel >> 0);
  cmd[5] = acc;
  cmd[6] = (uint8)(clk >> 24);
  cmd[7] = (uint8)(clk >> 16);
  cmd[8] = (uint8)(clk >> 8);
  cmd[9] = (uint8)(clk >> 0);
  cmd[10] = raF;
  cmd[11] = 0;
  cmd[12] = 0x6B;

  motor_save_cmd(cmd, 13);
}

