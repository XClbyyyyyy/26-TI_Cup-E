//-------------------------------------------------------------------------------------------------------------------
void motor_origin_trigger_return(uint8 addr, uint8 origin_mode)
{
  uint8 cmd[5] = {0};  // 回零触发完整协议命令

  cmd[0] = addr;
  cmd[1] = 0x9A;
  cmd[2] = origin_mode;
  cmd[3] = 0;
  cmd[4] = 0x6B;

  motor_save_one_shot_cmd(cmd, 5);
}
