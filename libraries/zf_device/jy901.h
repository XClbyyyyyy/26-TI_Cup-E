#ifndef _JY901_H_
#define _JY901_H_

#include "zf_common_headfile.h"

//-------------------------------------------------------------------------------------------------------------------
// 接收结构体
//-------------------------------------------------------------------------------------------------------------------
typedef struct
{
  uint8 state;                    // 接收状态: 0=等待帧头, 1=等待类型, 2=接收帧数据
  uint8 rx_buf[9];                // 当前正在接收的帧数据: 8字节数据+1字节校验
  uint8 rx_len;                   // 当前帧已接收的字节数
  uint8 data_type;                // 当前帧类型: 0x52=角速度, 0x53=欧拉角
  volatile uint8 gyro_buf[9];     // 校验通过的角速度帧缓冲
  volatile uint8 angle_buf[9];    // 校验通过的欧拉角帧缓冲
  volatile uint8 gyro_ready;      // 角速度帧就绪标志: 0=无新帧, 1=待解析
  volatile uint8 angle_ready;     // 欧拉角帧就绪标志: 0=无新帧, 1=待解析
} jy901_rx_struct;

//-------------------------------------------------------------------------------------------------------------------
// 传感器数据结构体
//-------------------------------------------------------------------------------------------------------------------
typedef struct
{
  float gyro_x;    // X轴角速度(°/s)
  float gyro_y;    // Y轴角速度(°/s)
  float gyro_z;    // Z轴角速度(°/s), 已补偿零漂
  float angle_x;   // X轴角度(°)
  float angle_y;   // Y轴角度(°)
  float angle_z;   // Z轴角度(°)
} jy901_data_struct;

//-------------------------------------------------------------------------------------------------------------------
// 外部变量声明
//-------------------------------------------------------------------------------------------------------------------
extern jy901_rx_struct jy901_rx;
extern jy901_data_struct jy901_data;

//-------------------------------------------------------------------------------------------------------------------
// 函数声明
//-------------------------------------------------------------------------------------------------------------------
void jy901_init(void);
void jy901_rx_callback(uint32 state, void *ptr);
void jy901_process_data(void);
void jy901_zero_angle(void);

#endif